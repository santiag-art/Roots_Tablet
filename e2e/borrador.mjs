import { createRequire } from 'node:module';
const { chromium } = createRequire('/home/claude/.npm-global/lib/node_modules/')('playwright');
import { readFile } from 'node:fs/promises';
import { servir } from './servidor.mjs';
const RAIZ = new URL('..', import.meta.url).pathname;
const { s, puerto } = await servir(RAIZ);
const nav = await chromium.launch();
const page = await (await nav.newContext({ viewport: { width: 960, height: 600 }, hasTouch: true, acceptDownloads: true })).newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
const ok = (c, m) => { console.log(c ? 'ok:' : 'FALLA:', m); if (!c) errs.push(m); };
const vis = '.ventana-fondo:not(.saliendo) ';
await page.goto(`http://127.0.0.1:${puerto}/`);
await page.waitForSelector('.vacio');
const [ch] = await Promise.all([page.waitForEvent('filechooser'), page.click('.vacio .btn-primario')]);
await ch.setFiles(RAIZ + 'tests/fixtures/muestra-roots.json');
await page.click(vis + '.ventana-pie .btn-primario');
await page.waitForTimeout(300);
ok(!(await page.$('.banda:has-text("set en juego")')), 'sin set en juego no hay aviso de borrador');
// abrir el partido 10, elegir formato y anotar puntos
await page.evaluate(() => { location.hash = '#/partido/10'; });
await page.waitForSelector('.formato');
await page.click('text=Mejor de 3');
await page.waitForSelector('.indicador-guardado');
await page.click('[aria-label^="Punto para"] >> nth=0');
await page.click('[aria-label^="Punto para"] >> nth=0');
await page.waitForTimeout(300);
ok(/Guardado/.test(await page.textContent('#indicador-guardado')), 'el indicador dice Guardado');
const espejo = await page.evaluate(() => JSON.parse(localStorage.getItem('roots-espejo')));
ok(espejo?.partidos?.[0]?.est?.actual?.puntosLocal === 2, 'el espejo tiene los 2 puntos');
// el almacén principal "pierde" la última jugada: simulamos atrasándolo, y recargamos
await page.evaluate(async () => {
  const r = structuredClone(window.__roots.partidos.get(10));
  r.est.actual.puntosLocal = 1;
  r.est.actualizadoEn = '2000-01-01T00:00:00.000Z';
  await window.__roots.almacen.guardar('partidos', r);
  await window.__roots.almacen.pendientes();
});
await page.evaluate(() => { location.hash = '#/'; });
await page.reload();
await page.waitForSelector('.partido-tarjeta');
ok((await page.evaluate(() => window.__roots.partidos.get(10).est.actual.puntosLocal)) === 2, 'al reabrir se recupera lo último desde el espejo');
ok(!!(await page.$('.banda:has-text("set en juego")')), 'aparece el aviso de borrador en el inicio');
const [d] = await Promise.all([page.waitForEvent('download'), (async () => { await page.click('.banda >> text=Exportar borrador'); await page.click('.ventana-fondo:not(.saliendo) >> text=Guardar en la tablet'); })()]);
const texto = await readFile(await d.path(), 'utf8');
ok(/roots-borrador-/.test(d.suggestedFilename()), 'descarga ' + d.suggestedFilename());
await page.waitForTimeout(400);
ok(!(await page.$('.banda:has-text("set en juego")')), 'el aviso desaparece tras exportar');
// borrar todo y recuperar el borrador con Importar archivo
await page.click('[aria-label=Ajustes]');
await page.click(vis + '>> text=Borrar todos los datos');
await page.locator(vis + '.ventana-pie .btn-peligro').click(); await page.waitForTimeout(300);
await page.locator(vis + '.ventana-pie .btn-peligro').click(); await page.waitForTimeout(500);
ok((await page.evaluate(() => window.__roots.partidos.size)) === 0 && !(await page.evaluate(() => localStorage.getItem('roots-espejo'))), 'tablet vaciada y sin espejo');
await page.reload(); await page.waitForSelector('.vacio');
ok((await page.evaluate(() => window.__roots.partidos.size)) === 0, 'el espejo no resucita lo borrado a propósito');
const [ch2] = await Promise.all([page.waitForEvent('filechooser'), page.click('.vacio .btn-primario')]);
await ch2.setFiles({ name: 'borrador.json', mimeType: 'application/json', buffer: Buffer.from(texto) });
await page.waitForSelector(vis + '>> text=Recuperar el borrador');
await page.locator(vis + '.ventana-pie .btn-primario').click();
await page.waitForSelector(vis + '>> text=Borrador importado');
await page.locator(vis + '.ventana-pie .btn-primario').click();
await page.waitForTimeout(400);
ok((await page.evaluate(() => window.__roots.partidos.get(10)?.est.actual.puntosLocal)) === 2, 'el borrador devolvió el partido con sus 2 puntos');
console.log('ERRORES', errs);
await nav.close(); s.close(); process.exit(errs.length ? 1 : 0);
